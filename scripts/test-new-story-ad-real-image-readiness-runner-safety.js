#!/usr/bin/env node
'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const script = path.resolve(__dirname, 'run-new-story-ad-real-image-to-video-readiness.js');
const source = fs.readFileSync(script, 'utf8');
const denied = spawnSync(process.execPath, [script, '--budget-rmb=10'], { encoding: 'utf8' });
assert.notStrictEqual(denied.status, 0);
assert.match(`${denied.stdout}${denied.stderr}`, /REAL_IMAGE_PAID_CONFIRMATION_REQUIRED/);
const oversized = spawnSync(process.execPath, [script, '--confirm-paid', '--budget-rmb=10.01'], { encoding: 'utf8' });
assert.notStrictEqual(oversized.status, 0);
assert.match(`${oversized.stdout}${oversized.stderr}`, /REAL_IMAGE_BUDGET_MUST_BE_BETWEEN_0_AND_10_RMB/);
assert.match(source, /reservePerImageRmb = 2/);
assert.match(source, /maxImageSubmissions !== 3/);
assert.match(source, /NEW_STORY_AD_IMAGE_MAX_CANDIDATES = '1'/);
assert.match(source, /pipeline_model_config\.json/);
assert.match(source, /NEW_STORY_AD_V3_PAID_VIDEO_ENABLED = executeNarrativeVideo \? '1' : '0'/);
assert.match(source, /videoAdapter\.generateSceneBlockVideos = async/);
assert.match(source, /REAL_IMAGE_RUN_VIDEO_CALL_FORBIDDEN/);
assert.match(source, /verify-existing-run/);
assert.match(source, /\^\\d\{14\}\$/);
assert.match(source, /video_provider: 'deyunai'/);
assert.match(source, /video_model: 'doubao-seedance-2-0-260128'/);
assert.match(source, /paidBudget\.assertWithinBudget/);
assert.match(source, /singleAttempt: true/);
assert.match(source, /imageModel: 'deyunai\/gpt-image-2'/);
const videoWithoutExistingImage = spawnSync(process.execPath, [script, '--execute-narrative-video', '--confirm-paid-video', '--video-budget-rmb=20.70', '--public-image-url=https://example.invalid/a.png'], { encoding: 'utf8' });
assert.notStrictEqual(videoWithoutExistingImage.status, 0);
assert.match(`${videoWithoutExistingImage.stdout}${videoWithoutExistingImage.stderr}`, /REAL_VIDEO_EXISTING_IMAGE_RUN_REQUIRED/);
const videoWithoutConfirmation = spawnSync(process.execPath, [script, '--execute-narrative-video', '--verify-existing-run=20260813173109', '--video-budget-rmb=20.70', '--public-image-url=https://example.invalid/a.png'], { encoding: 'utf8' });
assert.notStrictEqual(videoWithoutConfirmation.status, 0);
assert.match(`${videoWithoutConfirmation.stdout}${videoWithoutConfirmation.stderr}`, /REAL_VIDEO_PAID_CONFIRMATION_REQUIRED/);
const oversizedVideo = spawnSync(process.execPath, [script, '--execute-narrative-video', '--verify-existing-run=20260813173109', '--confirm-paid-video', '--video-budget-rmb=20.71', '--public-image-url=https://example.invalid/a.png'], { encoding: 'utf8' });
assert.notStrictEqual(oversizedVideo.status, 0);
assert.match(`${oversizedVideo.stdout}${oversizedVideo.stderr}`, /REAL_VIDEO_BUDGET_MUST_BE_BETWEEN_0_AND_20_70_RMB/);
assert.match(source, /executeNarrativeVideo \? '1' : '0'/);
assert.match(source, /NEW_STORY_AD_VIDEO_MAX_CANDIDATES = '1'/);
assert.match(source, /audit\.video_provider_calls_started >= 3/);
assert.match(source, /cost_plan_fingerprint: plan\.cost_plan\.fingerprint/);
assert.match(source, /confirmed_cost_limit_rmb: videoBudgetRmb/);
assert.match(source, /automatic_paid_retry_count \|\| 0\), 0/);
assert.match(source, /seedance_input_mode: 'first_frame'/);
assert.match(source, /generateVideoStage\s*\(/);
assert.match(source, /composeStage\s*\(/);
console.log(JSON.stringify({ passed: true, image_budget_cap_rmb: 10, fixed_image_submissions: 3, one_candidate_per_image: true, default_paid_video_hard_disabled: true, narrative_video_budget_cap_rmb: 20.70, narrative_video_max_provider_calls: 3, automatic_paid_retry_count: 0, exact_route_and_cost_fingerprint_required: true }));
