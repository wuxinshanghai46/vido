'use strict';
const assert = require('assert');
const prompt = require('../src/services/newStoryAd/personGenerationPromptService');
const compiler = require('../src/services/newStoryAd/personDossierCompiler');
const runtime = require('../src/services/newStoryAd/personGenerationRuntimeContractService');
const identity = require('../src/services/newStoryAd/personIdentityContractService');
const media = require('../src/services/newStoryAd/mediaAdapter');
const fs = require('fs');
const path = require('path');

const ad = prompt.normalizeSettings({}, { content_mode: 'commercial_subject' });
const story = prompt.normalizeSettings({}, { content_mode: 'narrative_story' });
assert.deepEqual(ad, { model: 'gpt-image-2', aspect_ratio: 'auto', quality: 'standard', resolution: '2K', count: 1, generation_type: 'three_view' });
assert.equal(story.generation_type, 'global_dossier');
assert.equal(prompt.normalizeSettings({ count: 99 }).count, 1);
const three = compiler.generationPlan(ad), four = compiler.generationPlan({ generation_type: 'four_view' }), global = compiler.generationPlan({ generation_type: 'global_dossier' });
assert.deepEqual(three.categorySpecs[0].keys, ['front', 'side', 'back']);
assert.deepEqual(four.categorySpecs[0].keys, ['front', 'side', 'back', 'action']);
assert.equal(global.expectedAtomicCount, compiler.EXPECTED_ATOMIC_COUNT);
const adapter = { requiredImageModelForStage: () => 'gpt-image-2', availableImageCandidates: () => [{ provider_id: 'webang-maas', model_id: 'gpt-image-2' }] };
const compactRuntime = runtime.inspect({ generation_settings: ad }, { mediaAdapter: adapter });
assert.equal(compactRuntime.estimated_provider_calls, 3);
assert.equal(compactRuntime.expected_output_assets, 5);
assert.deepEqual(compactRuntime.supported_resolutions, ['1K', '2K']);
assert.deepEqual(identity.requiredPersonViewKeys({ generation_type: 'three_view' }, {}), ['front', 'side', 'back']);
assert.deepEqual(identity.requiredPersonViewKeys({ generation_type: 'four_view' }, {}), ['front', 'side', 'back', 'action']);
const body = media.buildWebangGptImage2GenerationBody({ modelId: 'gpt-image-2' }, { prompt: '人物三视图', size: '1536x1024', quality: 'standard' });
assert.equal(body.quality, 'medium');
assert.equal(body.n, 1);
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
const sceneActions = read('public/story-ad/views/sceneCardInteractions.js');
const sceneSettings = read('public/story-ad/views/sceneDossierCardSettings.js');
const sceneService = read('src/services/newStoryAd/sceneAssetService.js');
assert(sceneActions.includes('sceneGenerationSettingsMarkup'));
assert(sceneSettings.includes('data-scene-quality') && sceneSettings.includes('data-scene-resolution'));
assert(sceneSettings.includes('value="720P"'));
assert(sceneSettings.includes('4K（当前模型不支持）') && sceneSettings.includes('value="4K" disabled'));
assert(/(?:event\.target|target)\.value\s*===\s*'low'\s*\?\s*'720P'\s*:\s*'2K'/.test(sceneActions));
assert(sceneActions.includes('aspect_ratio: aspectRatio, count: 1'));
assert(sceneService.includes("quality: body.quality || 'standard'"));
console.log(JSON.stringify({ passed: true, ad_default: ad.generation_type, story_default: story.generation_type, provider_calls: { three_view: 3, four_view: 3, global_dossier: 6 }, quantity_per_group: 1, paid_model_calls: 0 }));
